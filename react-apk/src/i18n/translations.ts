export type TranslationKey = keyof typeof TRANSLATIONS;

export function t(key: TranslationKey, lang: LanguageCode = 'en'): string {
  const entry = TRANSLATIONS[key];
  if (!entry) return key;
  return (entry as any)[lang] || entry.en || key;
}

/** React hook returning translation helper bound to current selected language. */
export function useTranslation() {
  const language = usePlayerStore(state => state.language ?? 'en');
  const setLanguage = usePlayerStore(state => state.setLanguage);

  return {
    language,
    setLanguage,
    t: (key: TranslationKey) => t(key, language),
    isRtl: Boolean(LANGUAGES[language]?.rtl),
    currentLanguageInfo: LANGUAGES[language] ?? LANGUAGES.en,
  };
}
